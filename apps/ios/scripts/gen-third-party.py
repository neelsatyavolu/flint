#!/usr/bin/env python3
"""Writes THIRD-PARTY.md from the catalog the app shows in Settings > About > Licenses.

Usage: python3 -I scripts/gen-third-party.py [--check]
The single source is App/Features/Settings/ThirdPartyLicenses.json (packages in Package.resolved that the app links,
bundled fonts, icons). --check exits 1 when THIRD-PARTY.md is out of date.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "App/Features/Settings/ThirdPartyLicenses.json"
OUT = ROOT / "THIRD-PARTY.md"
RESOLVED = ROOT / "Packages/FlintCore/Package.resolved"
# Linked packages that vendor code under a licence of its own: the catalog must carry that text too.
VENDORED = {"swift-nio-ssl": ("BoringSSL", ["OpenSSL License", "Original SSLeay License", "ISC license", "fiat-crypto"])}


def problems(catalog: dict) -> list[str]:
    """What is wrong with the catalog compared with Package.resolved: missing vendored licence texts, stale versions."""
    found = []
    items = {item["name"]: item for item in catalog["items"]}
    pins = {p["identity"]: p["state"] for p in json.loads(RESOLVED.read_text())["pins"]}
    for identity, (prefix, needles) in VENDORED.items():
        if identity not in pins:
            continue
        item = next((i for n, i in items.items() if n.startswith(prefix)), None)
        text = catalog["texts"].get(item["textId"], "") if item else ""
        found += [f"{identity} vendors {prefix}: licence text lacks '{n}'" for n in needles if n not in text]
    for identity, state in pins.items():
        item = items.get(identity)
        if item and item["version"] not in (state.get("version"), state["revision"][:7]):
            found.append(f"{identity}: catalog says {item['version']}, Package.resolved pins {state.get('version') or state['revision'][:7]}")
    return found


def render(catalog: dict) -> str:
    items, texts = catalog["items"], catalog["texts"]
    lines = [
        "# Third-party software in Flint for iOS",
        "",
        "Flint is MIT licensed. The app also ships the software below. This file is generated by",
        "`scripts/gen-third-party.py` from `App/Features/Settings/ThirdPartyLicenses.json`, the same catalog the app shows in",
        "Settings > About > Licenses. Do not edit it by hand.",
        "",
        "| Name | Version | License | Copyright |",
        "|---|---|---|---|",
    ]
    for item in items:
        copyright_line = " ".join(item["copyright"].split())
        lines.append(f"| {item['name']} | {item['version'] or 'bundled'} | {item['license']} | {copyright_line} |")
    lines += ["", "No QR library is bundled: the pairing scanner uses AVFoundation. Server-side Swift packages that the app does not link are not listed.", ""]
    by_text: dict[str, list[str]] = {}
    for item in items:
        by_text.setdefault(item["textId"], []).append(item["name"])
    for text_id, names in by_text.items():
        lines += [f"## License text: {', '.join(names)}", "", "```text", texts[text_id].rstrip(), "```", ""]
    notices = [(i["name"], i["notice"]) for i in items if i["notice"]]
    for name, notice in notices:
        lines += [f"## NOTICE: {name}", "", "```text", notice.rstrip(), "```", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    catalog = json.loads(CATALOG.read_text())
    text = render(catalog)
    issues = problems(catalog)
    for issue in issues:
        print(f"gen-third-party: {issue}", file=sys.stderr)
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text and not issues else 1)
    if issues:
        sys.exit(1)
    OUT.write_text(text)
