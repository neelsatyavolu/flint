#!/usr/bin/env bash
# Generates FlintHTML/TrackerRulesData.swift from the tracker table in packages/core/fixtures/trackers.json
# (which is itself generated from sanitize/trackers.ts by scripts/fixtures/update-data.sh).
#   gen-trackers.sh           rewrite the Swift file
#   gen-trackers.sh --check   exit 1 when the Swift file is stale (CI; TrackerRulesTests also catches drift)
set -euo pipefail
root="$(cd "$(dirname "$0")/../../.." && pwd)"
src="$root/packages/core/fixtures/trackers.json"
out="$root/apps/ios/Packages/FlintCore/Sources/FlintHTML/TrackerRulesData.swift"

render() {
  node --input-type=module - "$src" <<'JS'
import { readFileSync } from "node:fs";
const rules = JSON.parse(readFileSync(process.argv[2], "utf8")).rules;
const lines = rules.map((r) => {
  if (!r.path) return `        TrackerRule(host: "${r.host}"),`;
  if (r.path.flags !== "i") throw new Error(`unexpected regex flags for ${r.host}: ${r.path.flags}`);
  if (r.path.source.includes('"#')) throw new Error(`pattern for ${r.host} breaks the raw string`);
  return `        TrackerRule(host: "${r.host}", pathPattern: #"${r.path.source}"#),`;
});
process.stdout.write(`// Generated by apps/ios/scripts/gen-trackers.sh from packages/core/fixtures/trackers.json ("rules", itself generated
// from sanitize/trackers.ts). Do not edit by hand: change TRACKER_RULES in TypeScript, run
// scripts/fixtures/update-data.sh, apps/ios/scripts/sync-fixtures.sh and then gen-trackers.sh.
// TrackerFixtureTests.rulesTableMatchesSyncedFixture fails when this table drifts from the synced fixture.

extension TrackerRules {
    public static let all: [TrackerRule] = [
${lines.join("\n")}
    ]
}
`);
JS
}

case "${1:-}" in
  "") render > "$out"; echo "wrote ${out#"$root/"}" ;;
  --check)
    tmp="$(mktemp -t trackers.XXXXXX)"
    trap 'rm -f "$tmp"' EXIT
    render > "$tmp"
    cmp -s "$tmp" "$out" || { echo "TrackerRulesData.swift is stale: run apps/ios/scripts/gen-trackers.sh" >&2; exit 1; }
    echo "TrackerRulesData.swift is in sync"
    ;;
  *) echo "usage: gen-trackers.sh [--check]" >&2; exit 2 ;;
esac
