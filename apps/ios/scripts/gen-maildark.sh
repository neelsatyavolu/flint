#!/usr/bin/env bash
# Bundles the desktop dark-mode adapter (apps/desktop/.../lib/mailDark) for WKWebView.
#   gen-maildark.sh           rebuild apps/ios/App/Resources/mailDark.bundle.js
#   gen-maildark.sh --check   rebuild to a temp file and diff; exit 1 when the committed bundle is stale (CI)
# The bundle is committed so building the app needs no Node toolchain. Never hand-edit it.
set -euo pipefail
root="$(cd "$(dirname "$0")/../../.." && pwd)"
entry="$root/apps/ios/scripts/maildark-entry.ts"
out="$root/apps/ios/App/Resources/mailDark.bundle.js"

esbuild_bin="${ESBUILD:-}"
if [ -z "$esbuild_bin" ]; then
  for candidate in "$root/node_modules/.bin/esbuild" "$root/node_modules/.pnpm/node_modules/.bin/esbuild"; do
    [ -x "$candidate" ] && { esbuild_bin="$candidate"; break; }
  done
fi
[ -n "$esbuild_bin" ] || { echo "esbuild not found: run pnpm install or set ESBUILD" >&2; exit 2; }

build() {
  # iife + global side effect only; minified to keep the app small; target is Safari on iOS 26.
  "$esbuild_bin" "$entry" --bundle --format=iife --target=safari26 --minify --legal-comments=none \
    --banner:js="/* Generated by apps/ios/scripts/gen-maildark.sh from the desktop mailDark adapter. Do not edit. */" \
    --log-level=warning --outfile="$1"
}

case "${1:-}" in
  "")
    mkdir -p "$(dirname "$out")"
    build "$out"
    echo "wrote ${out#"$root/"} ($(wc -c < "$out" | tr -d ' ') bytes)"
    ;;
  --check)
    tmp="$(mktemp -t maildark.XXXXXX)"
    trap 'rm -f "$tmp"' EXIT
    build "$tmp"
    if [ ! -f "$out" ] || ! cmp -s "$tmp" "$out"; then
      echo "mailDark.bundle.js is stale: run apps/ios/scripts/gen-maildark.sh" >&2
      exit 1
    fi
    echo "mailDark.bundle.js is in sync"
    ;;
  *) echo "usage: gen-maildark.sh [--check]" >&2; exit 2 ;;
esac
