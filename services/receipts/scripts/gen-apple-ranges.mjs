// Regenerates src/apple-ranges.ts from Apple's published egress list.
// Usage: node scripts/gen-apple-ranges.mjs [path-to-egress-ip-ranges.csv]
// Without an argument it downloads https://mask-api.icloud.com/egress-ip-ranges.csv.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SOURCE = "https://mask-api.icloud.com/egress-ip-ranges.csv";
const csv = process.argv[2] ? await readFile(process.argv[2], "utf8") : await (await fetch(SOURCE)).text();

function expand6(ip) {
  const [head, tail] = ip.split("::");
  const h = head ? head.split(":") : [];
  const t = tail ? tail.split(":") : [];
  const fill = tail === undefined ? 0 : 8 - h.length - t.length;
  return [...h, ...Array(fill).fill("0"), ...t].map((g) => g.padStart(4, "0")).join("");
}

const v4 = new Set();
const v6 = new Set();
for (const line of csv.split("\n")) {
  const cidr = line.split(",")[0]?.trim();
  if (!cidr) continue;
  const [ip, lenRaw] = cidr.split("/");
  const len = Number(lenRaw);
  if (ip.includes(":")) {
    // Every CSV prefix is /40 or longer, so the covering /36 block is a sound coarse key.
    v6.add(expand6(ip).slice(0, 9));
  } else {
    if (len < 24) throw new Error(`unexpected IPv4 prefix shorter than /24: ${cidr}`);
    const [a, b, c] = ip.split(".").map(Number);
    v4.add(a * 65536 + b * 256 + c);
  }
}

const out = `// GENERATED by scripts/gen-apple-ranges.mjs from ${SOURCE} on ${new Date().toISOString().slice(0, 10)}. Do not edit.
// IPv4: /24 blocks as (a << 16 | b << 8 | c). IPv6: first 9 hex digits (/36) of the expanded address.
export const APPLE_RELAY_V4_24: readonly number[] = [${[...v4].sort((x, y) => x - y).join(",")}];
export const APPLE_RELAY_V6_36: readonly string[] = ${JSON.stringify([...v6].sort())};
`;
const target = fileURLToPath(new URL("../src/apple-ranges.ts", import.meta.url));
await writeFile(target, out);
console.log(`wrote ${target}: ${v4.size} IPv4 /24 blocks, ${v6.size} IPv6 /36 blocks`);
